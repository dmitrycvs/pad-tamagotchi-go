-- Data warehouse (Lab 5): star schema of Tamagotchi Go, filled by the etl-service.
-- Runs on the first start of an empty data-warehouse volume.
--
-- Every dimension has a surrogate key and an "unknown" row with key 0. Natural ids are text, because
-- the services use both uuid and text. A fact that arrives before its dimension row adds a placeholder
-- (only the id); the next load of the dimension fills it in.

CREATE TABLE dim_date (
    date_key    integer PRIMARY KEY,          -- 20261124
    full_date   date NOT NULL UNIQUE,
    year        smallint NOT NULL,
    quarter     smallint NOT NULL,
    month       smallint NOT NULL,
    month_name  text NOT NULL,
    day         smallint NOT NULL,
    day_of_week smallint NOT NULL,            -- ISO: 1 = Monday
    day_name    text NOT NULL,
    is_weekend  boolean NOT NULL
);

INSERT INTO dim_date
SELECT to_char(d, 'YYYYMMDD')::integer, d::date, extract(year FROM d), extract(quarter FROM d), extract(month FROM d),
       to_char(d, 'FMMonth'), extract(day FROM d), extract(isodow FROM d), to_char(d, 'FMDay'), extract(isodow FROM d) >= 6
FROM generate_series(timestamp '2020-01-01', timestamp '2039-12-31', interval '1 day') AS d;

-- Package Registry: packages
CREATE TABLE dim_package (
    package_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id  text NOT NULL UNIQUE,
    name        text NOT NULL DEFAULT 'Unknown',
    version     text,
    status      text,
    created_at  timestamptz,
    updated_at  timestamptz
);

-- User Management: "Users" and "UserPackages" (no email or password hash)
CREATE TABLE dim_user (
    user_key          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           text NOT NULL UNIQUE,
    username          text NOT NULL DEFAULT 'Unknown',
    home_package_key  bigint NOT NULL DEFAULT 0 REFERENCES dim_package,
    home_package_name text NOT NULL DEFAULT 'Unknown',
    package_count     integer NOT NULL DEFAULT 0,
    registered_at     timestamptz
);

-- Tamagotchi: tamagotchis
CREATE TABLE dim_tamagotchi (
    tamagotchi_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tamagotchi_id  text NOT NULL UNIQUE,
    name           text NOT NULL DEFAULT 'Unknown',
    type           text,
    level          integer,
    xp             bigint,
    is_primary     boolean,
    owner_user_key bigint NOT NULL DEFAULT 0 REFERENCES dim_user,
    package_key    bigint NOT NULL DEFAULT 0 REFERENCES dim_package,
    package_name   text NOT NULL DEFAULT 'Unknown',
    created_at     timestamptz,
    updated_at     timestamptz
);

-- Guild: guilds and guild_members
CREATE TABLE dim_guild (
    guild_key      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id       text NOT NULL UNIQUE,
    name           text NOT NULL DEFAULT 'Unknown',
    owner_user_key bigint NOT NULL DEFAULT 0 REFERENCES dim_user,
    member_count   integer NOT NULL DEFAULT 0,
    created_at     timestamptz,
    updated_at     timestamptz
);

